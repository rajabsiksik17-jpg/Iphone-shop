export type AdminKey = keyof typeof d;
export type AdminT = (key: AdminKey, vars?: Record<string, string | number>) => string;

export function adminT(locale: string): AdminT {
  const i = locale === "ar" ? 1 : 0;
  return (key, vars) => {
    const raw: string = d[key]?.[i] ?? key;
    return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? "")) : raw;
  };
}

export const hasAdminKey = (k: string): k is AdminKey => k in d;
